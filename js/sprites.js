const DIGITS = {
  0: ['111', '101', '101', '101', '111'], 1: ['010', '110', '010', '010', '111'],
  5: ['111', '100', '111', '001', '111'],
};
function drawDigits(ctx, text, x, y, color) {
  ctx.fillStyle = color;
  [...text].forEach((d, i) => {
    DIGITS[d].forEach((row, ry) => [...row].forEach((v, rx) => {
      if (v === '1') ctx.fillRect(x + i * 4 + rx, y + ry, 1, 1);
    }));
  });
}

