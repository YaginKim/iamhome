function person(key, hair, hairShade, top, topShade, bottom, extra) {
  const body = PERSON(hair, hairShade, top, topShade, bottom, extra);
  return [
    gridCanvas(body + LEGS_A(bottom), key + '0'),
    gridCanvas(body + LEGS_B(bottom), key + '1'),
  ];
}

